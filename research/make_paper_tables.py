def summary_table(metric, name, ns=NS):
    """Rows = methods; columns = 6 benchmarks + Dev / External / All; best per column in bold."""
    vals, names = [], []
    for k, lab in METHODS:
        s = cm(D[k], metric, ns)
        cols = []
        for b in BENCH:
            cb = [c for c in CATS if bench(c) == b]
            cols.append(s[cb].mean() if complete(s, cb) else np.nan)
        for cs in (DEVC, EXT, CATS):
            cols.append(s[cs].mean() if complete(s, cs) else np.nan)
        vals.append(cols)
        names.append(lab)
    best = [max((v[j] for v in vals if not np.isnan(v[j])), default=np.nan) for j in range(len(vals[0]))]
    lines = []
    for lab, v in zip(names, vals):
        cells = ["---" if np.isnan(x) else ("\\textbf{" + f1(x) + "}" if f1(x) == f1(best[j]) else f1(x)) for j, x in enumerate(v)]
        lines.append(f"{lab} & " + " & ".join(cells) + " \\\\")
    (OUT / f"{name}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {k: cm(D[k], metric, ns) for k, _ in METHODS}


