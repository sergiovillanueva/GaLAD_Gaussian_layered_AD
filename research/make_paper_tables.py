def cm(d, metric, ns=NS, cats=CATS):
    """Category means over draws and the given N (NaN for a category that misses any N)."""
    d = d[d.n_train.isin(ns) & d.dataset.isin(cats)].dropna(subset=[metric])
    if d.empty:
        return pd.Series(np.nan, index=cats)
    t = d.groupby(["dataset", "n_train"])[metric].mean().unstack("n_train").reindex(index=cats, columns=ns)
    return t.mean(axis=1, skipna=False) * 100


def paired(x, y):
    d = (x - y).dropna()
    g = np.random.default_rng(0)
    bs = [g.choice(d.values, len(d)).mean() for _ in range(10000)]
    return d.mean(), np.percentile(bs, 2.5), np.percentile(bs, 97.5), (d > .5).sum(), (d.abs() <= .5).sum(), (d < -.5).sum(), len(d)


def cell(pr):
    return f"${pr[0]:+.1f}$ [${pr[1]:+.1f}$, ${pr[2]:+.1f}$]", f"{pr[3]}/{pr[4]}/{pr[5]}"


def complete(s, cats):
    return s.reindex(cats).notna().all()


