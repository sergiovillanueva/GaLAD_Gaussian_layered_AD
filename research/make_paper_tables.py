"""LaTeX tables and in-text numbers of the Electronics manuscript (version of 9 Oct 2026), from the saved CSVs.

Paper scope (PAPER_PLAN.md): 55 categories of MVTec AD and VisA (development) and AutoVI, BTAD, GoodsAD, MVTec LOCO
and the public test of MVTec AD 2 (external evaluation); N = 1, 2, 4, 5 references, 5 draws; methods AnomalyDINO
(official configuration), AnomalyDINO (DINOv3-L), PatchCore (WideResNet-50) and GaLAD.

Writes paper/electronics/tables/*.tex (tabular bodies), tables/numbers.tex (\\newcommand macros used by the
text) and tables/numbers.md (the same numbers, readable). Points = 100 x metric. Category means first (draws,
then N), then means over categories. Paired differences: per category, 95% bootstrap CI over categories
(10,000 resamples, seed 0), W/T/L with a 0.5-point margin. A method enters an aggregate only when it covers
every category and N of that aggregate.

GaLAD source: the final runs (output/server/final_square.csv, EM <= 30 iterations, PCA keeping the leading
components). --provisional uses the earlier runs (l_square + new_square) so the script can be checked before
the final runs end.

Usage: uv run make_paper_tables.py [--provisional]
"""

