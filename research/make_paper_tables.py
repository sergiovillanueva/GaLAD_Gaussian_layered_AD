def mac(name, value, fmt="{:.1f}", text=None):
    v = fmt.format(value) if not isinstance(value, str) else value
    macros[name] = v.replace("-", "$-$") if v.startswith("-") else v
    notes.append(f"- `\\{name}` = {v}" + (f"  ({text})" if text else ""))


def f1(v):
    """One decimal, but 100 instead of 100.0 (as in the authors' published tables)."""
    s = f"{v:.1f}"
    return "100" if s == "100.0" else s


